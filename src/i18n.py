"""Traducao simples da interface (estilo gettext): portugues (padrao) e ingles.

`_()` usa o proprio texto em portugues como chave. Com o idioma "pt" (padrao) ou
quando o texto nao esta no dicionario `EN`, devolve o texto igual ao original,
para nao quebrar nada que ja dependia da string em portugues. Com "en", devolve
a traducao. Textos com variaveis usam `str.format` com campos nomeados:

    _("Pausado: {msg}.", msg=motivo)

O idioma e fixado uma vez, ao abrir a macro (`set_language`), a partir de
`cfg["ui"]["language"]`: trocar depois pode pedir para reabrir a macro.
"""
from __future__ import annotations

_lang = "pt"


def set_language(lang: str) -> None:
    """Define o idioma atual ("pt" ou "en"; qualquer outra coisa vira "pt")."""
    global _lang
    _lang = "en" if lang == "en" else "pt"


def get_language() -> str:
    return _lang


def _(text_pt: str, **fmt) -> str:
    """Traduz `text_pt` para o idioma atual e aplica `str.format(**fmt)` se houver campos."""
    text = EN.get(text_pt, text_pt) if _lang == "en" else text_pt
    return text.format(**fmt) if fmt else text


